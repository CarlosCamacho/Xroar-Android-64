#!/usr/bin/env python3
"""Generate RomCatalog.java from XRoar's own ROM table (src/rom.c).

    tools/gen_romcatalog.py <xroar-source-dir> > RomCatalog.java

The app uses it to recognise a ROM or cartridge file by its CRC-32: which
slot it belongs in (Color BASIC, Extended BASIC, disk controller), what to
name the file so XRoar's romlists find it, and the title of a Program Pak.
Only the CoCo entries are kept (not Dragon, MC-10 or Deluxe CoCo).
"""
import re, sys

src = open(sys.argv[1] + "/src/rom.c", encoding="utf-8").read()
entries = []
for m in re.finditer(r'\{\s*DESC\((0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+)\s*,\s*"([^"]*)"\)\s*,([^\n]*?)\},', src):
    crc, size, desc, rest = int(m.group(1), 16), int(m.group(2), 16), m.group(3), m.group(4)
    kind = name = None
    coco3 = False
    if "P_COCO," in rest + "," and desc.startswith("Colour BASIC"):
        kind = "BASIC"
        v = re.search(r"S_BAS(1[0-3])", rest)
        if "Dynacom" in desc:
            name = "mx1600bas_zephyr" if "zephyr" in desc else "mx1600bas"
        else:
            name = "bas" + (v.group(1) if v else "10")
    elif "P_COCO," in rest + "," and desc.startswith("Extended Colour BASIC"):
        kind = "EXT"
        name = "mx1600extbas" if "Dynacom" in desc else ("extbas10" if "1.0" in desc else "extbas11")
    elif "P_RSDOS" in rest:
        kind = "DOS"
        name = "disk10" if "1.0" in desc and "Disk Extended" in desc else "disk11"
    elif ("P_ROM" in rest or "P_GMC" in rest) and re.search(r"M_COCO(12|3)?\b|machine = \"coco3,coco\"", rest):
        kind = "GMC" if "P_GMC" in rest else "PAK"   # GMC: runs in a Games Master Cartridge
        name = ""
        coco3 = "M_COCO3" in rest or "coco3" in rest and "M_COCO12" not in rest and "M_COCO," not in rest
        if "M_COCO," in rest or "M_COCO12" in rest or 'machine = "coco3,coco"' in rest:
            coco3 = False
    if kind:
        entries.append((crc, size, kind, name, desc, coco3))

print("// GENERATED by tools/gen_romcatalog.py from XRoar's src/rom.c.  Do not edit.")
print("package io.github.carloscamacho.xroar;")
print()
print("import java.util.HashMap;")
print("import java.util.Map;")
print()
print("/* Known CoCo ROMs and Program Paks, by CRC-32.  kind is BASIC, EXT, DOS, PAK or GMC;")
print(" * name is the file name (without extension) XRoar's romlists look for;")
print(" * coco3 marks a Pak that needs a CoCo 3. */")
print("final class RomCatalog {")
print("    static final class Entry {")
print("        final long crc;")
print("        final int size;")
print("        final String kind, name, desc;")
print("        final boolean coco3;")
print()
print("        Entry(long crc, int size, String kind, String name, String desc, boolean coco3) {")
print("            this.crc = crc; this.size = size; this.kind = kind; this.name = name; this.desc = desc; this.coco3 = coco3;")
print("        }")
print("    }")
print()
print("    private static final Object[][] TABLE = {")
for crc, size, kind, name, desc, coco3 in entries:
    d = desc.replace("\\", "\\\\").replace('"', '\\"')
    print(f'        {{ 0x{crc:08x}L, {size}, "{kind}", "{name}", "{d}", {"true" if coco3 else "false"} }},')
print("    };")
print()
print("    private static final Map<Long, Entry> BY_CRC = new HashMap<>();")
print("    static {")
print("        for (Object[] r : TABLE) {")
print("            BY_CRC.put((Long) r[0], new Entry((Long) r[0], (Integer) r[1], (String) r[2], (String) r[3], (String) r[4], (Boolean) r[5]));")
print("        }")
print("    }")
print()
print("    static Entry byCrc(long crc) {")
print("        return BY_CRC.get(crc);")
print("    }")
print("}")
sys.stderr.write(f"{len(entries)} entries: " + ", ".join(f"{k}={sum(1 for e in entries if e[2]==k)}" for k in ('BASIC','EXT','DOS','PAK','GMC')) + "\n")
