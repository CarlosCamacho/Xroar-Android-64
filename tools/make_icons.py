def vector_xml(shapes):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Generated by tools/make_icons.py; edit that, not this. Tinted at run time. -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="24dp" android:height="24dp"',
           '    android:viewportWidth="24" android:viewportHeight="24">']
    for kind, d in shapes:
        if kind == "fill":
            out.append(f'    <path android:fillColor="#FF000000" android:fillType="evenOdd"\n'
                       f'        android:pathData="{d}" />')
        else:
            out.append(f'    <path android:strokeColor="#FF000000" android:strokeWidth="2.2"\n'
                       f'        android:strokeLineCap="round" android:strokeLineJoin="round"\n'
                       f'        android:pathData="{d}" />')
    out.append('</vector>')
    return "\n".join(out) + "\n"

def svg(shapes, size=72, color="#222"):
    body = []
    for kind, d in shapes:
        if kind == "fill":
            body.append(f'<path fill="{color}" fill-rule="evenodd" d="{d}"/>')
        else:
            body.append(f'<path fill="none" stroke="{color}" stroke-width="2.2" stroke-linecap="round" '
                        f'stroke-linejoin="round" d="{d}"/>')
    return f'<svg viewBox="0 0 24 24" width="{size}" height="{size}">{"".join(body)}</svg>'

def main():
    here = os.path.dirname(os.path.abspath(__file__))
    dest = os.path.join(here, "..", "android", "app", "src", "main", "res", "drawable")
    for name, shapes in ICONS.items():
        with open(os.path.join(dest, name + ".xml"), "w") as f:
            f.write(vector_xml(shapes))
    if "--preview" in sys.argv:
        path = sys.argv[sys.argv.index("--preview") + 1]
        cells = "".join(f'<div style="display:inline-block;width:110px;text-align:center;margin:6px;'
                        f'font:11px sans-serif">{svg(s)}<br>{n}</div>' for n, s in ICONS.items())
        with open(path, "w") as f:
            f.write(f'<html><body style="background:#fff;margin:8px">{cells}</body></html>')
    print(len(ICONS), "icons")

if __name__ == "__main__":
    main()
